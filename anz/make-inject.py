#!/usr/bin/env python3
"""Builds anz/inject.js from anz/index.html: the ANZ lift as one script for Readymag's code injection.

Paste into the Readymag project's custom code (end of <body>):
    <script type="module" src="https://henri-cmd.github.io/lift-demo/anz/inject.js"></script>

The script draws the cab over the Readymag site, fits the site's stacked pages into the doorway and uses them as the floors.
It does nothing (the site is left exactly as it is) on touch devices, small windows, inside an iframe,
or if the project is not set to stack its pages vertically. The page numbering in anz/pagenumbers.js is built in and runs everywhere. Without WebGL it shows the 2D picture lift.   Re-run after editing index.html:   python3 anz/make-inject.py
"""
import os, re, json
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'index.html'), encoding='utf-8').read()

css = '\n'.join(re.findall(r'<style[^>]*>(.*?)</style>', src, re.S))
css = re.sub(r'^html,body\{[^}]*\}\s*$', '', css, flags=re.M)
css += '''
/* hosted in another site: only the cab is drawn, and everything but the lift's own controls lets the pointer through */
#lift3d{position:fixed !important; inset:0 !important; z-index:2147480000; background:transparent !important; pointer-events:none}
#lift3d .ui{pointer-events:auto}
#lift3d .loading{pointer-events:auto}
#lift3d .loading.done{pointer-events:none}
#lift3d .css3d{display:none}
'''
a = src.index('<div id="lift3d">'); b = src.index('<script type="importmap">')
skeleton = src[a:b].strip()
mod = re.search(r'<script type="module">(.*?)</script>', src, re.S).group(1)
imports = re.findall(r"^import .*?;\s*$", mod, re.M)
assert len(imports) == 5, imports
for line in imports: mod = mod.replace(line, '')

prelude = r'''/* ANZ lift for Readymag code injection. Generated by anz/make-inject.py from anz/index.html: do not edit by hand. */
const BASE = new URL('../', import.meta.url).href, never = () => new Promise(() => {});
// page numbers first: they run everywhere, including where the lift itself stays away (phones, small windows)
try {
__PAGENUMBERS__
} catch (e) { console.warn('[pg]', e); }
if (window.__liftBase) await never();
window.__liftBase = BASE;
{ const g = document.createElement('script'); g.src = BASE + 'assets/finch-gate.js'; document.head.appendChild(g); }   // the Finch viewing gate (it decides for itself when to show)
{ // leave the site alone where the lift cannot or should not run
  let gl = null; try { gl = document.createElement('canvas').getContext('webgl2'); } catch (e) {}
  const safari = /Safari\//.test(navigator.userAgent) && !/Chrom|Edg\/|OPR\/|CriOS|FxiOS|EdgiOS|Android/.test(navigator.userAgent) && !navigator.maxTouchPoints && !/[?&]3d\b/.test(location.search);   // Safari on a computer gets the 2D lift too (?3d forces the 3D one)
  if (!gl || safari || /[?&](nogl|flat)\b/.test(location.search)) window.__flat = true;   // no 3D graphics: the lift is put together from pictures instead
  if (window.top !== window || matchMedia('(pointer: coarse)').matches || Math.min(innerWidth, innerHeight) < 600) await never();
}
const mag = await new Promise(res => { const t0 = Date.now(); (function poll() {
  const R = window.RM, m = R && R.viewerRouter && R.viewerRouter.mag, el = document.querySelector('main.mag');
  if (m && m.pages && m.pages.length && el && el.querySelector('article.page')) return res(m);
  if (Date.now() - t0 > 20000) return res(null); setTimeout(poll, 100); })(); });
if (!mag || !document.querySelector('main.mag.viewer-type-vertical')) await never();
{ const P = window.CanvasRenderingContext2D && CanvasRenderingContext2D.prototype;
  if (P && !P.roundRect) P.roundRect = function (x, y, w, h, r) { r = Math.min(typeof r === 'number' ? r : (r && r[0]) || 0, Math.abs(w) / 2, Math.abs(h) / 2);
    this.moveTo(x + r, y); this.arcTo(x + w, y, x + w, y + h, r); this.arcTo(x + w, y + h, x, y + h, r); this.arcTo(x, y + h, x, y, r); this.arcTo(x, y, x + w, y, r); this.closePath(); }; }
const liftCss = document.createElement('style'); liftCss.textContent = __CSS__; document.head.appendChild(liftCss);
document.body.insertAdjacentHTML('beforeend', __SKELETON__);
{ const magEl = document.querySelector('main.mag'), fitCss = document.createElement('style'), tail = document.createElement('div');
  document.head.appendChild(fitCss); tail.style.cssText = 'position:absolute;left:0;width:1px;pointer-events:none'; document.body.appendChild(tail);
  window.__liftHost = {
    el: magEl,
    floors: mag.pages.map((p, i) => ({ n: String(p.title || '').trim() || 'Page ' + (i + 1), bg: '#111' })),
    fit(x, y, w, fixed) { fitCss.textContent = `main.mag{position:${fixed ? 'fixed' : 'absolute'} !important; left:${x.toFixed(1)}px !important; top:${y.toFixed(1)}px !important; width:${w}px !important} html{background:#0b0d10 !important}`; },
    height() { return magEl.offsetHeight; },
    // pages further down are hidden until you get near them, so they measure as nothing: the site records where each one sits in its style
    tops() { const out = []; let y = 0; for (const a of magEl.querySelectorAll('article.page')) { const t = parseFloat(a.style.top), h = a.offsetHeight || parseFloat(a.style.height) || 0; y = isFinite(t) ? t : h && a.offsetHeight ? a.offsetTop : y; out.push(y); y += h; } return out; },
    tail(h) { tail.style.top = '0'; tail.style.height = h + 'px'; },
  };
  // if the lift has not appeared after a while, take it away again so the site is usable
  setTimeout(() => { const l = document.querySelector('#lift3d .loading'); if (l && !l.classList.contains('done')) { document.getElementById('lift3d').remove(); fitCss.remove(); tail.remove(); dispatchEvent(new Event('resize')); } }, 20000);
}
const THREE = await import(BASE + 'assets/vendor/three/three.module.js');
const { RoomEnvironment } = await import(BASE + 'assets/vendor/three/addons/environments/RoomEnvironment.js');
const { RectAreaLightUniformsLib } = await import(BASE + 'assets/vendor/three/addons/lights/RectAreaLightUniformsLib.js');
const { RoundedBoxGeometry } = await import(BASE + 'assets/vendor/three/addons/geometries/RoundedBoxGeometry.js');
const { Reflector } = await import(BASE + 'assets/vendor/three/addons/objects/Reflector.js');
'''
pagenumbers = open(os.path.join(here, 'pagenumbers.js'), encoding='utf-8').read()
out = prelude.replace('__PAGENUMBERS__', pagenumbers).replace('__CSS__', json.dumps(css)).replace('__SKELETON__', json.dumps(skeleton)) + mod
open(os.path.join(here, 'inject.js'), 'w', encoding='utf-8').write(out)
print('wrote anz/inject.js', len(out))
